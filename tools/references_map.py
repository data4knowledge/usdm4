"""Generate src/usdm4/fixer/references.py from the CDISC DDF-RA dataStructure.yml.

The USDM model marks every id-reference attribute with ``Relationship Type: Ref``
and lists the class or classes it may point at. Superclasses (ScheduledInstance,
StudyDesign) carry ``Sub Classes``. Both are written out as Python dicts so the
package needs no copy of the YAML at run time.

Source: https://github.com/cdisc-org/DDF-RA, tag v4.0.0,
Deliverables/UML/dataStructure.yml (downloaded by hand).

    python3 tools/references_map.py --source /path/dataStructure.yml [--tag v4.0.0]
"""

import argparse
import pathlib
import pprint

import yaml

OUTPUT = (
    pathlib.Path(__file__).resolve().parents[1]
    / "src"
    / "usdm4"
    / "fixer"
    / "references.py"
)


def _name(ref: dict) -> str:
    return ref["$ref"].removeprefix("#/")


def build(structure: dict) -> tuple[dict, dict]:
    references = {}
    sub_classes = {}
    for klass, definition in structure.items():
        subs = definition.get("Sub Classes") or []
        if subs:
            sub_classes[klass] = sorted(_name(s) for s in subs)
        for attribute, info in (definition.get("Attributes") or {}).items():
            if info.get("Relationship Type") != "Ref":
                continue
            targets = sorted(_name(t) for t in info.get("Type") or [])
            references.setdefault(klass, {})[attribute] = targets
    return references, sub_classes


def render(references: dict, sub_classes: dict, tag: str) -> str:
    return (
        "# Generated by tools/references_map.py, do not edit.\n"
        f"# Source: CDISC DDF-RA {tag}, Deliverables/UML/dataStructure.yml.\n"
        "# REFERENCES: class -> id-reference attribute -> target classes.\n"
        "# SUB_CLASSES: superclass -> concrete subclasses.\n\n"
        f"SOURCE = {tag!r}\n\n"
        f"REFERENCES = {pprint.pformat(references, width=88, sort_dicts=True)}\n\n"
        f"SUB_CLASSES = {pprint.pformat(sub_classes, width=88, sort_dicts=True)}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", required=True, help="path to dataStructure.yml")
    parser.add_argument("--tag", default="v4.0.0", help="DDF-RA tag of the source")
    args = parser.parse_args()
    with open(args.source) as f:
        structure = yaml.safe_load(f)
    references, sub_classes = build(structure)
    OUTPUT.write_text(render(references, sub_classes, args.tag))
    count = sum(len(v) for v in references.values())
    print(f"{count} reference attributes, {len(sub_classes)} superclasses -> {OUTPUT}")


if __name__ == "__main__":  # pragma: no cover
    main()
