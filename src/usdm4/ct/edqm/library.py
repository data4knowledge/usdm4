"""EDQM (ISO 11239) pharmaceutical dose forms (GitHub 104).

Reads ``dose_forms.yaml``, generated by ``tools/edqm_ct.py`` from the NCI EVS
EDQM-HealthCare Terminology Subsets. Data from the EDQM Standard Terms
database (http://standardterms.edqm.eu), reproduced with the permission of
the European Directorate for the Quality of Medicines & HealthCare, Council
of Europe (EDQM); see the file header for the release and retrieval dates.
"""

import os
from functools import lru_cache

import yaml

DOSE_FORMS_FILE = os.path.join(os.path.dirname(__file__), "dose_forms.yaml")


@lru_cache(maxsize=1)
def _load(path: str = DOSE_FORMS_FILE) -> dict:
    with open(path, encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    data["by_term"] = {
        " ".join(t["term"].split()).lower(): t for t in data.get("terms") or []
    }
    return data


def code_system() -> str:
    return _load()["codeSystem"]


def version() -> str:
    """The retrieval date: the EDQM database is not a static list."""
    return _load()["retrieved"]


def dose_form(text: str) -> dict | None:
    """The EDQM dose form ``text`` names, ignoring case and outer spaces:
    ``{"code", "term", "ncit"}``, or None."""
    if not text:
        return None
    return _load()["by_term"].get(" ".join(str(text).split()).lower())
